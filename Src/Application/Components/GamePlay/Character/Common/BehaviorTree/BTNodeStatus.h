#pragma once

// ============================================================
// ビヘイビアツリーの各ノードがTick()のたびに返す実行結果。
//
// StateMachineのState(Enter/Update/Exitで「今どの状態か」を管理する)とは
// 発想が異なり、BTノードは「1回のTickで何が起きたか」を都度返し、
// それを親(Composite)側が解釈して子の実行順序・打ち切りを判断する。
// ============================================================
enum class BTNodeStatus
{
	Success, // このノードの行動は完了し、成功した
	Failure, // このノードの行動は実行できない、または失敗した
	Running, // まだ実行中(次フレームも同じノードから継続して評価する)
};
